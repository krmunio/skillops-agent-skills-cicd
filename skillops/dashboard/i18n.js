let locale = 'en';
const storageKey = 'skillops.dashboard.locale';
const texts = new Map(), attributes = new Map();
class Message {
  constructor(render) { this.render = render; }
  toString() { return this.render(); }
}
export function t(parts, ...values) {
  const key = typeof parts === 'string' ? parts : parts.reduce((text, part, i) =>
    text + part + (i < values.length ? `{${i}}` : ''), '');
  return new Message(() => (locale === 'en' ? english[key] ?? key : key)
    .replace(/\{(\d+)\}/g, (_, index) => typeof values[index] === 'number' ?
      new Intl.NumberFormat(locale === 'ko' ? 'ko-KR' : 'en-US').format(values[index]) : String(values[index])));
}
export const join = (values, separator = ' · ') => new Message(() => values.map(String).join(separator));
export const formatted = render => new Message(() => render(locale === 'ko' ? 'ko-KR' : 'en-US'));
export function setText(element, value) {
  const text = document.createTextNode(String(value));
  element.replaceChildren(text);
  if (value instanceof Message) texts.set(text, value);
}
export function setAttribute(element, name, value) {
  element.setAttribute(name, String(value));
  if (value instanceof Message) {
    if (!attributes.has(element)) attributes.set(element, new Map());
    attributes.get(element).set(name, value);
  } else attributes.get(element)?.delete(name);
}
function update() {
  document.documentElement.lang = locale;
  for (const [text, message] of texts) {
    if (text.isConnected) text.data = String(message);
    else texts.delete(text);
  }
  for (const [element, messages] of attributes) {
    if (!element.isConnected) { attributes.delete(element); continue; }
    for (const [name, message] of messages) element.setAttribute(name, String(message));
  }
}
export function setupLanguage() {
  let unavailable = false;
  try {
    const saved = localStorage.getItem(storageKey);
    locale = saved === 'ko' ? 'ko' : 'en';
  } catch { unavailable = true; }
  for (const element of document.querySelectorAll('[data-i18n]')) setText(element, t(element.dataset.i18n));
  for (const element of document.querySelectorAll('[data-i18n-aria-label]')) {
    setAttribute(element, 'aria-label', t(element.dataset.i18nAriaLabel));
  }
  for (const element of document.querySelectorAll('[data-i18n-content]')) {
    setAttribute(element, 'content', t(element.dataset.i18nContent));
  }
  const select = document.getElementById('language-select'), status = document.getElementById('language-status');
  const notice = () => {
    status.hidden = !unavailable;
    setText(status, t('언어 설정을 저장할 수 없습니다. 이번 방문에서만 적용됩니다.'));
  };
  select.value = locale;
  select.addEventListener('change', () => {
    locale = select.value === 'ko' ? 'ko' : 'en';
    try { localStorage.setItem(storageKey, locale); unavailable = false; }
    catch { unavailable = true; }
    notice(); update();
  });
  notice(); update();
}
